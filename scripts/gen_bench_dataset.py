#!/usr/bin/env python3
"""
gen_bench_dataset.py — 生成合成 IMU 数据集供滤波器基准测试

生成 1000 帧合成数据，覆盖 4 个阶段：
  1. 静止 (frames 0-249):    ACC=[0,0,1g], GYRO=[0,0,0]
  2. 慢转 (frames 250-499):  pitch 从 0°→45°, roll=0, yaw 线性旋转 90°
  3. 振动 (frames 500-749):  静止 + 10Hz 正弦振动 (模拟电机)
  4. 阶跃 (frames 750-999):  姿态阶跃：突然倾斜 30° 然后保持

输出: test/bench_dataset.h — const filter_input_t bench_data[1000]
"""

import math
import os

DT = 0.01  # 采样间隔 (秒), 100Hz
G = 1.0    # 1g

def gen_dataset():
    data = []
    for i in range(1000):
        ax, ay, az = 0.0, 0.0, 1.0  # default: flat
        gx, gy, gz = 0.0, 0.0, 0.0

        if i < 250:
            # Phase 1: 静止，水平放置
            pass  # all zeros

        elif i < 500:
            # Phase 2: 慢转
            t_idx = i - 250  # 0..249
            frac = t_idx / 250.0  # 0..1 over 2.5 sec
            # pitch: 0 → 45° with smooth start/stop
            pitch_deg = 45.0 * (3*frac**2 - 2*frac**3)  # smoothstep
            pitch_rad = math.radians(pitch_deg)
            ax = math.sin(pitch_rad)
            az = math.cos(pitch_rad)  # 归一化: |g|=1
            # gyro: pitch rate
            pitch_rate = 45.0 * 6 * (frac - frac**2) / 2.5  # derivative of smoothstep
            gy = math.radians(pitch_rate) * 180.0 / math.pi  # deg/s → keep in dps
            # yaw: linear
            yaw_rate = 90.0 / 2.5  # 36°/s
            gz = yaw_rate

        elif i < 750:
            # Phase 3: 静止 + 振动
            t_idx = i - 500
            # 10Hz, 0.3g 幅值正弦振动 (模拟电机振动)
            vib = 0.3 * math.sin(2 * math.pi * 10 * t_idx * DT)
            ax += vib * 0.3  # 主要在 X 轴
            ay += vib * 0.2  # Y 轴也有分量
            # gyro 噪声：±2 dps 随机白噪近似
            gy += vib * 2.0
            gz += vib * 1.0

        else:
            # Phase 4: 阶跃
            t_idx = i - 750
            if t_idx < 20:  # 保持静止 0.2s
                pass
            elif t_idx < 30:  # 0.1s 内倾斜到 30° roll
                roll_deg = 30.0
                roll_rad = math.radians(roll_deg)
                ay = math.sin(roll_rad)
                az = math.cos(roll_rad)
                gx = -roll_deg / 0.1  # dps
            else:  # 保持 30° roll
                roll_rad = math.radians(30.0)
                ay = math.sin(roll_rad)
                az = math.cos(roll_rad)

        # 加微小随机噪声 (LSM6DSR 典型噪声: ACC 0.08mg/√Hz, GYRO 0.01dps/√Hz @ 100Hz BW)
        import random
        ax += random.gauss(0, 0.0008)
        ay += random.gauss(0, 0.0008)
        az += random.gauss(0, 0.0008)
        gx += random.gauss(0, 0.01)
        gy += random.gauss(0, 0.01)
        gz += random.gauss(0, 0.01)

        data.append((ax, ay, az, gx, gy, gz))

    return data


def write_header(data, path):
    with open(path, "w") as f:
        f.write("/* Auto-generated by scripts/gen_bench_dataset.py — DO NOT EDIT */\n")
        f.write("/* 1000 帧合成 IMU 数据：静止/慢转/振动/阶跃 */\n")
        f.write("/* 采样率: 100Hz, dt=0.01s */\n\n")
        f.write("#ifndef BENCH_DATASET_H\n#define BENCH_DATASET_H\n\n")
        f.write('#include "filter.h"\n\n')
        f.write("static const filter_input_t bench_data[1000] = {\n")
        for i, (ax, ay, az, gx, gy, gz) in enumerate(data):
            if i % 5 == 0:
                f.write("    /* %3d */ " % i)
            f.write(f"{{{ax:.6f}f,{ay:.6f}f,{az:.6f}f,{gx:.6f}f,{gy:.6f}f,{gz:.6f}f,0.01f}}")
            if i < 999:
                f.write(",")
            if (i + 1) % 5 == 0:
                f.write("\n")
        f.write("\n};\n\n")
        f.write("#endif /* BENCH_DATASET_H */\n")
    print(f"Generated {path} ({len(data)} frames)")


def main():
    script_dir = os.path.dirname(os.path.abspath(__file__))
    project_root = os.path.dirname(script_dir)
    test_dir = os.path.join(project_root, "test")

    data = gen_dataset()
    write_header(data, os.path.join(test_dir, "bench_dataset.h"))


if __name__ == "__main__":
    main()
